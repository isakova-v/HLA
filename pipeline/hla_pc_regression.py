"""
HLA + PCs regression for vaccine titers (per vaccine, per gene with reference allele)

- Input vaccination TSV: contains quantitative titre columns (e.g., measles_ME_ml, rubella_ME_ml,
  diphtheria_ME_ml, HBV_antiHBsAg_ME_ml), vaccine flags (e.g., measles_vaccine_info == 1),
  and principal components PC1..PC20.

- Input HLA Excel: wide format with per-gene columns like A_1, A_2, B_1, B_2, ..., and an ID
  column named `sample_id` (can be customized).

- Model per vaccine:
    y = log1p(titer) ~ sum_{gene}(alleles_except_ref) + PCs
  where `alleles_except_ref` are allele dosage columns (0,1,2) for all alleles in a gene
  that pass the frequency threshold; the *most frequent allele within that gene* is dropped
  to serve as a reference (baseline).

- Outputs:
    out_dir/
      combined_coeffs.csv               # all vaccines stacked
      <vaccine_key>_coeffs.csv          # per-vaccine coefficients
      <vaccine_key>_design_stats.csv    # per-vaccine basic stats (N, num alleles kept, etc.)

Author: generated by ChatGPT
"""

import argparse
import math
import os
import re
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

# Statsmodels for OLS with robust SE
import statsmodels.api as sm

